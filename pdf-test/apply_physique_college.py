def apply_canonical(text, pattern_dict, none_patterns):
    """Find canonical form. Returns None if should be removed, '' if no match, string otherwise."""
    if not text or not str(text).strip(): return None
    s = normalize_ar(text)
    if not s: return None
    # Check for none patterns
    for p in none_patterns:
        if p.lower() in text.lower():
            return None
    best = None
    best_len = 0
    for canonical, patterns in pattern_dict.items():
        for p in patterns:
            if p in s and len(p) > best_len and len(p) >= 3:
                best = canonical
                best_len = len(p)
    return best if best else s  # if no match, return normalized text (so we still save it)


