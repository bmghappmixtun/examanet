#!/usr/bin/env node
/**
 * scripts/generate-bac-manifest.mjs
 *
 * Reads /tmp/probed-manifest.json and enriches it with subject metadata,
 * then writes:
 *  - public/data/bac-manifest.json (full version with subjectMeta)
 *  - src/data/bac-manifest.ts (slim, embed-at-build version)
 *
 * Run after: node scripts/probe-bac-manifest.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();

// Load existing manifest for metadata
const existingManifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'public/data/bac-manifest.json'), 'utf-8'));

// Build subject metadata map from existing
const subjectMeta = {};
for (const u of existingManifest.uploaded || []) {
  if (u.subject && u.subjectMeta && !subjectMeta[u.subject]) {
    subjectMeta[u.subject] = u.subjectMeta;
  }
}

// Add metadata for new subjects
const additionalMeta = {
  'sport': { nameFr: 'Sport', nameAr: 'الرياضة', color: 'orange' },
  'musique_a': { nameFr: 'Musique (Arabe)', nameAr: 'الموسيقى', color: 'pink' },
};
Object.assign(subjectMeta, additionalMeta);

// Load probed data
const probed = JSON.parse(fs.readFileSync('/tmp/probed-manifest.json', 'utf-8'));

// Enrich entries
const enriched = probed.map((e) => ({
  ...e,
  subjectCode: e.subject,
  subjectMeta: subjectMeta[e.subject] || { nameFr: e.subject, nameAr: e.subject, color: 'gray' },
}));

// Sort by year DESC, session (principale first), section, subject
enriched.sort((a, b) => {
  if (a.year !== b.year) return b.year - a.year;
  if (a.session !== b.session) return a.session === 'principale' ? -1 : 1;
  if (a.section !== b.section) return a.section.localeCompare(b.section);
  return a.subject.localeCompare(b.subject);
});

const minYear = Math.min(...enriched.map(e => e.year));
const maxYear = Math.max(...enriched.map(e => e.year));

const newManifest = {
  generatedAt: new Date().toISOString(),
  site: 'examanet.com',
  namespace: 'bac',
  source: 'bacweb.tn',
  minYear,
  maxYear,
  uploaded: enriched,
};

// Save full version
fs.writeFileSync(
  path.join(ROOT, 'public/data/bac-manifest.json'),
  JSON.stringify(newManifest, null, 2)
);
console.log(`Wrote public/data/bac-manifest.json (${enriched.length} entries)`);

// Save slim version (essential fields only)
const slim = {
  ...newManifest,
  uploaded: enriched.map(e => ({
    key: e.key,
    url: e.url,
    size: e.size,
    year: e.year,
    section: e.section,
    sectionRaw: e.sectionRaw,
    session: e.session,
    type: e.type,
    subject: e.subject,
  })),
};

const ts = `// Auto-generated by scripts/embed-bac-manifest.ts
// Embedded data from /public/data/bac-manifest.json (slim version)
// (fs.readFileSync doesn't work at runtime on CF Workers)
export const BAC_MANIFEST = ${JSON.stringify(slim, null, 2)};
`;

fs.writeFileSync(
  path.join(ROOT, 'src/data/bac-manifest.ts'),
  ts
);
console.log(`Wrote src/data/bac-manifest.ts (${(ts.length / 1024 / 1024).toFixed(2)}MB)`);

// Stats
const byYear = {};
for (const e of enriched) {
  byYear[e.year] = (byYear[e.year] || 0) + 1;
}
console.log('\nBy year:');
for (const [y, c] of Object.entries(byYear).sort()) {
  console.log(`  ${y}: ${c}`);
}
